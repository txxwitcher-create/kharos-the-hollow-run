export function getCharacterById(id: string): CharacterDef {
  return CHARACTERS.find((c) => c.id === id) ?? CHARACTERS[0];
}

export function getOutfitsForCharacter(characterId: string): OutfitDef[] {
  return OUTFITS.filter((o) => o.characterId === characterId);
}

